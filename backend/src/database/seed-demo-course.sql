CREATE OR REPLACE FUNCTION assign_demo_course_to_user(user_telegram_id BIGINT)
RETURNS INTEGER AS $$
DECLARE
  new_course_id INTEGER;
  demo_catalog_id INTEGER;
BEGIN
  -- Получить ID демо-курса из каталога
  SELECT id INTO demo_catalog_id
  FROM catalog_courses
  WHERE is_demo = true
  LIMIT 1;

  IF demo_catalog_id IS NULL THEN
    RAISE EXCEPTION 'Demo course not found in catalog';
  END IF;

  -- Создать курс для пользователя
  INSERT INTO courses (
    user_id,
    catalog_course_id,
    title,
    description,
    status,
    progress_percent,
    is_paid
  )
  SELECT
    (SELECT id FROM users WHERE telegram_id = user_telegram_id),
    demo_catalog_id,
    'Нейросети. База',
    'Бесплатный демо-курс',
    'active',
    0,
    true -- Бесплатный курс сразу "оплачен"
  RETURNING id INTO new_course_id;

  -- Создать темы курса
  INSERT INTO course_topics (course_id, title, description, order_index)
  SELECT
    new_course_id,
    title,
    description,
    order_index
  FROM demo_course_topics
  ORDER BY order_index;

  -- Создать уроки для каждой темы
  INSERT INTO lessons (
    topic_id,
    title,
    content,
    lesson_type,
    duration_minutes,
    order_index
  )
  SELECT
    ct.id,
    dl.title,
    dl.content,
    'text',
    dl.duration_minutes,
    dl.order_index
  FROM demo_course_lessons dl
  JOIN demo_course_topics dt ON dl.topic_id = dt.id
  JOIN course_topics ct ON ct.course_id = new_course_id AND ct.title = dt.title
  ORDER BY dl.order_index;

  RETURN new_course_id;
END;
$$ LANGUAGE plpgsql;

